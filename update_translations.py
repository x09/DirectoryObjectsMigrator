def build_catalogue(lang: str, lang_name: str, msgids) -> str:
    lines = [HEADER.format(
        lang=lang,
        lang_name=lang_name,
        date=datetime.now().strftime('%Y-%m-%d %H:%M%z') or datetime.now().strftime('%Y-%m-%d %H:%M'),
    )]

    for msgid in sorted(msgids):
        if lang == 'en':
            # The msgid already is the English text; make it explicit
            msgstr = msgid
        else:
            msgstr = RU.get(msgid, '')
        lines.append(f'msgid "{po_escape(msgid)}"')
        lines.append(f'msgstr "{po_escape(msgstr)}"')
        lines.append('')

    return '\n'.join(lines)


